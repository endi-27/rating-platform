from enum import StrEnum


class ReviewStatus(StrEnum):
    """Статуси життєвого циклу та модерації відгуку."""

    PUBLISHED = "published"  # Опублікований відгук (за замовчуванням). Враховується в розрахунку рейтингу.
    HIDDEN = "hidden"  # Прихований модератором через порушення (не враховується в рейтингу).
    FLAGGED = "flagged"  # Позначений як підозрілий або на розгляді модератора.
